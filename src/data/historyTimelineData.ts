export type EraKey = 'old_democratic' | 'new_democratic' | 'socialist_revolution' | 'reform_new_era'
export type ItemCategory = 'meeting' | 'event' | 'work' | 'policy'

export interface HistoryEra {
  key: EraKey
  name: string
  shortName: string
  startYear: number
  endYear: number
  themeColor: string
  badgeClass: string
  bgSoftClass: string
  coreContradiction: string
  historicalTask: string
}

export interface HistoryIllustration {
  title: string
  subtitle: string
  tag: string
  accentColor: string
  symbolIcon: string
  figureQuote?: string
}

export interface HistoryItem {
  id: string
  year: number
  date: string
  location?: string
  /** 地理坐标点 [经度 lng, 纬度 lat]，用于全屏历史大地图发光标绘 */
  coordinates?: [number, number]
  cityName?: string
  title: string
  category: ItemCategory
  era: EraKey
  /** 考研一字千金定性标签（如：生死攸关的转折点、开天辟地的大事变） */
  keyTag: string
  /** 核心内容、决议或纲领 */
  content: string
  /** 考研标准历史意义与定性表述 */
  significance: string
  /** 考研单选/多选高频命题陷阱与易混辨析 */
  pitfall?: string
  /** 重要程度：5 为必背超核心，4 为高频考点，3 为基础脉络 */
  importance: 5 | 4 | 3
  /** 考研历史视觉配图卡片 */
  illustration?: HistoryIllustration
}

export interface ComparisonMatrix {
  id: string
  title: string
  subtitle: string
  headers: string[]
  rows: string[][]
}

