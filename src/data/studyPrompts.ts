export function extractFollowUpPrompts(
  text: string,
  agentDomain: 'cs_408' | 'math' | 'vault' | 'quiz' | 'code' | string,
  count = 4
): { topic: string; prompts: string[] } | null {
  if (!text || text.trim().length === 0) return null

  const lower = text.toLowerCase()
  let pool: TopicFollowUp[] = []

  if (agentDomain === 'math') {
    pool = MATH_TOPIC_FOLLOWUPS
  } else {
    // 默认或 408 优先匹配 408 图谱，兼顾数学
    pool = [...CS408_TOPIC_FOLLOWUPS, ...MATH_TOPIC_FOLLOWUPS]
  }

  // 寻找最佳匹配的主题（命中关键词最多者）
  let bestMatch: TopicFollowUp | null = null
  let maxScore = 0

  for (const item of pool) {
    let score = 0
    for (const kw of item.keywords) {
      if (lower.includes(kw.toLowerCase())) {
        score += kw.length >= 4 ? 3 : 2
      }
    }
    if (score > maxScore) {
      maxScore = score
      bestMatch = item
    }
  }

  if (bestMatch && maxScore >= 2) {
    // 过滤掉与用户输入完全一模一样的提问，确保是真正的“后续发散追问”
    const filtered = bestMatch.prompts.filter(p => !lower.includes(p.toLowerCase().slice(0, 15)))
    const resultPrompts = (filtered.length >= 2 ? filtered : bestMatch.prompts).slice(0, count)
    return {
      topic: bestMatch.topicName,
      prompts: resultPrompts
    }
  }

  return null
}

/**
 * 随机打乱并获取 N 个元素
 */
function sampleRandom<T>(array: T[], n: number): T[] {
  const shuffled = [...array].sort(() => 0.5 - Math.random())
  return shuffled.slice(0, n)
}

/**
 * 根据智能体 ID 获取一组随机换批次的考点提问
 */
export function getRandomPromptsForAgent(agentId: string, count = 4): string[] {
  if (agentId === 'agent-math') {
    return sampleRandom(MATH_PROMPTS_POOL, count)
  }
  if (agentId === 'agent-vault') {
    return sampleRandom(VAULT_PROMPTS_POOL, count)
  }
  if (agentId === 'agent-quiz') {
    return sampleRandom(QUIZ_PROMPTS_POOL, count)
  }
  if (agentId === 'agent-code') {
    return sampleRandom(CODE_PROMPTS_POOL, count)
  }
  return sampleRandom(CS408_PROMPTS_POOL, count)
}
